def upgrade() -> None:
    # 1. Broaden the slug UNIQUE constraint. The original (created in 0009)
    #    is autogenerated as ``companies_slug_key`` by Postgres.
    op.drop_constraint("companies_slug_key", "companies", type_="unique")
    op.create_unique_constraint(
        "uq_companies_slug_source", "companies", ["slug", "source"]
    )

    # 2. Seed the new (source, slug) rows. Use raw SQL with a parameter
    #    list — Alembic's bulk_insert doesn't support ON CONFLICT.
    for source, slug, display in _NEW_COMPANIES:
        op.execute(
            f"""
            INSERT INTO companies (slug, display_name, source, enabled)
            VALUES ('{slug}', '{display.replace("'", "''")}', '{source}', true)
            ON CONFLICT (slug, source) DO NOTHING
            """
        )


def downgrade() -> None:
    # Best-effort row removal first so the original UNIQUE can be restored
    # without conflict.
    for source, slug, _display in _NEW_COMPANIES:
        op.execute(
            f"DELETE FROM companies WHERE slug='{slug}' AND source='{source}'"
        )
    op.drop_constraint(
        "uq_companies_slug_source", "companies", type_="unique"
    )
    op.create_unique_constraint("companies_slug_key", "companies", ["slug"])
