"""seed lever / ashby / workable companies, broaden companies.slug uniqueness

Two related changes in one migration:

1. Drop the global UNIQUE on ``companies.slug`` and replace it with a
   composite UNIQUE on ``(slug, source)``. The original constraint
   assumed every slug was globally unique, which breaks the moment
   ``linear`` exists on both Greenhouse and Ashby. The composite is the
   correct identity for an ATS-hosted company row.

2. Insert a small starter allowlist for the new ATS families so the
   scheduler has something to ingest the first time it ticks against any
   of them. Existing greenhouse rows are untouched. Inserts are guarded
   by ``ON CONFLICT (slug, source) DO NOTHING`` so re-running the
   migration (in tests, or on a partially-populated DB) is a no-op.

Revision ID: 0012_seed_lever_ashby_workable
Revises: 0011_application_verify
"""
